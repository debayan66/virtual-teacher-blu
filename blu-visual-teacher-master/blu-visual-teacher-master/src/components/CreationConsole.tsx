import { motion } from 'framer-motion';
import { useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Icon } from './Icon';
import { Button, Pill, Segmented, cx } from './ui';
import { LanguagePicker } from './LanguagePicker';
import { api, describeApiError } from '../lib/api';
import { LANGUAGES, offlineState } from '../lib/languages';
import { useStore } from '../lib/store';
import { findVoice, useDeviceVoices } from '../lib/voices';
import type { Level } from '../lib/types';

const LEVELS: { value: Level; label: string; title: string }[] = [
  { value: 'beginner', label: 'Beginner', title: 'Gentle pace, plain language' },
  { value: 'intermediate', label: 'Intermediate', title: 'Assumes prior context' },
  { value: 'advanced', label: 'Advanced', title: 'Dense, technical framing' },
];

const DURATIONS = [
  { value: '1', label: '1 min' },
  { value: '3', label: '3 min' },
  { value: '5', label: '5 min' },
  { value: '10', label: '10 min' },
];

const SUGGESTIONS = [
  'How a firewall protects a network',
  'The derivative, visually',
  'Photosynthesis in 60 seconds',
];

interface Props {
  topic: string;
  onTopic: (v: string) => void;
  level: Level;
  onLevel: (v: Level) => void;
  minutes: string;
  onMinutes: (v: string) => void;
  narration: string;
  onNarration: (v: string) => void;
  captions: string;
  onCaptions: (v: string) => void;
}

export function CreationConsole(p: Props) {
  const { backend, notify, openLesson, probe } = useStore();
  const { voices } = useDeviceVoices();
  const navigate = useNavigate();
  const [state, setState] = useState<'idle' | 'working' | 'failed'>('idle');
  const [error, setError] = useState<{ kind: string; status?: number; message: string } | null>(null);

  const readyCount = useMemo(
    () => LANGUAGES.filter((l) => offlineState(l, Boolean(findVoice(voices, l.code))) === 'ready').length,
    [voices],
  );

  const valid = p.topic.trim().length >= 3;

  async function generate() {
    if (!valid || state === 'working') return;
    setState('working');
    setError(null);
    const res = await api.generateLesson({
      topic: p.topic.trim(),
      level: p.level,
      minutes: Number(p.minutes),
      narration: p.narration,
      captions: p.captions,
    });
    if (res.ok) {
      setState('idle');
      notify('ok', 'Lesson generated by the local backend.');
      navigate('/library');
      return;
    }
    setState('failed');
    setError(res.error);
    notify('err', 'The local backend did not generate a lesson.');
  }

  return (
    <section className="console panel cut-br" aria-labelledby="console-title">
      <header className="console-head">
        <div>
          <span className="micro">Lesson console</span>
          <h2 id="console-title">Create an animated lesson</h2>
        </div>
        <Pill tone={backend === 'online' ? 'ok' : 'warn'} icon={backend === 'online' ? 'check' : 'cloudOff'}>
          {backend === 'online' ? 'Backend live' : 'Sample mode'}
        </Pill>
      </header>

      <div className="console-body">
        <div className="field">
          <label className="field-label" htmlFor="topic">
            <span>Topic</span>
            <span>{p.topic.trim().length} chars</span>
          </label>
          <textarea
            id="topic"
            className="textarea"
            value={p.topic}
            onChange={(e) => p.onTopic(e.target.value)}
            placeholder="e.g. How a firewall protects a network"
            rows={3}
            spellCheck={false}
          />
          <div className="suggests">
            <span className="micro">Try</span>
            {SUGGESTIONS.map((s) => (
              <button key={s} type="button" className="suggest" onClick={() => p.onTopic(s)}>
                {s}
              </button>
            ))}
          </div>
        </div>

        <div className="console-row">
          <div className="field">
            <span className="field-label">Learning level</span>
            <Segmented
              ariaLabel="Learning level"
              options={LEVELS}
              value={p.level}
              onChange={p.onLevel}
            />
          </div>
          <div className="field">
            <span className="field-label">
              <span>Duration</span>
              <span>≈ scenes</span>
            </span>
            <Segmented
              ariaLabel="Lesson duration"
              options={DURATIONS}
              value={p.minutes}
              onChange={p.onMinutes}
            />
          </div>
        </div>

        <div className="console-row">
          <LanguagePicker
            label="Narration"
            hint="voice"
            value={p.narration}
            onChange={p.onNarration}
            id="narration-lang"
          />
          <LanguagePicker
            label="Captions"
            hint="track"
            value={p.captions}
            onChange={p.onCaptions}
            id="caption-lang"
          />
        </div>

        <div className="offline-chip" title="Languages fully usable without internet on this device">
          <span className="orbit" aria-hidden="true">
            <i />
          </span>
          <span className="offline-chip-text">
            <b>{readyCount} of {LANGUAGES.length} languages offline-ready</b>
            <i>
              {findVoice(voices, p.narration)
                ? `Narration voice installed · ${findVoice(voices, p.narration)!.name}`
                : 'No installed voice for the selected narration language'}
            </i>
          </span>
          <button type="button" className="link" onClick={() => navigate('/languages')}>
            Manage
          </button>
        </div>

        {state === 'failed' && error && (
          <motion.div
            className="console-error"
            initial={{ opacity: 0, height: 0 }}
            animate={{ opacity: 1, height: 'auto' }}
            transition={{ duration: 0.26, ease: [0.16, 1, 0.3, 1] }}
            role="alert"
          >
            <Icon name="alert" size={17} />
            <div>
              <b>{describeApiError(error.kind, error.status)}</b>
              <p>{error.message}</p>
              <div className="console-error-actions">
                <Button size="sm" icon="refresh" onClick={() => void generate()}>
                  Retry connection
                </Button>
                <Button size="sm" variant="ghost" onClick={() => void probe()}>
                  Probe backend
                </Button>
                <Button size="sm" variant="primary" icon="play" onClick={() => { openLesson('sample-firewall'); navigate('/studio'); }}>
                  Open the sample lesson
                </Button>
              </div>
            </div>
          </motion.div>
        )}

        <button
          className={cx('generate-btn', state === 'working' && 'is-working')}
          onClick={() => void generate()}
          disabled={!valid || state === 'working'}
        >
          <span className="generate-btn-sweep" aria-hidden="true" />
          <span className="generate-btn-inner">
            {state === 'working' ? (
              <>
                <Icon name="refresh" size={17} className="spin" />
                Planning scenes…
              </>
            ) : (
              <>
                <Icon name="spark" size={17} />
                Generate lesson
                <Icon name="arrowRight" size={17} />
              </>
            )}
          </span>
        </button>

        <p className="console-foot">
          {backend === 'online'
            ? 'Runs on your local backend — nothing is sent to the cloud.'
            : 'The local backend is not reachable, so generation is disabled until it responds. The sample lesson stays available.'}
        </p>
      </div>
    </section>
  );
}